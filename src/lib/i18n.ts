const dicts: Record<Language, Dict> = { "zh-CN": zh, "en-US": en };

export function t(lang: Language, key: string, vars?: Record<string, string>): string {
  let text = dicts[lang][key] ?? dicts["zh-CN"][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

export function formatFloatMessage(lang: Language, message: string): string {
  const key = Object.keys(zh).find((k) => k.startsWith("floatbar.") && zh[k] === message);
  if (!key) return message;
  return dicts[lang][key] ?? message;
}
